function postResponseScript(definition: RequestDefinition): string {
  const capture = captureScript(definition.capture);
  return `pm.test('HTTP request succeeded', function () {
  pm.expect(pm.response.code).to.be.within(200, 299);
});
if (pm.response.code !== 204 && pm.response.text()) {
  let body;
  try { body = pm.response.json(); } catch (_) { body = undefined; }
  if (body) {
    ${capture}
  }
}
`;
}

function createRequest(definition: RequestDefinition) {
  const urlPath = definition.path;
  const isOperational =
    definition.path.startsWith('/health') ||
    definition.path.startsWith('/metrics') ||
    definition.path === '/openapi.json';
  const base = isOperational ? '{{baseUrl}}' : '{{baseUrl}}/api/v1';
  const query = definition.query
    ? `?${Object.entries(definition.query)
        .map(([key, value]) => `${key}=${value}`)
        .join('&')}`
    : '';
  const headers = Object.entries(definition.headers ?? {}).map(([key, value]) => ({
    key,
    value,
    type: 'text',
  }));
  if (definition.body && !headers.some((header) => header.key.toLowerCase() === 'content-type')) {
    headers.push({ key: 'Content-Type', value: 'application/json', type: 'text' });
  }
  if (definition.idempotent) {
    headers.push({ key: 'Idempotency-Key', value: '{{$guid}}', type: 'text' });
  }
  const events: Array<Record<string, unknown>> = [];
  if (definition.preRequest) {
    events.push({
      listen: 'prerequest',
      script: { type: 'text/javascript', exec: definition.preRequest.trim().split('\n') },
    });
  }
  events.push({
    listen: 'test',
    script: {
      type: 'text/javascript',
      exec: postResponseScript(definition).trim().split('\n'),
    },
  });
  return {
    name: definition.name,
    description: definition.description,
    request: {
      ...(bearerAuth(definition.auth ?? 'none')
        ? { auth: bearerAuth(definition.auth ?? 'none') }
        : {}),
      method: definition.method,
      header: headers,
      url: `${base}${urlPath}${query}`,
      ...(definition.body
        ? {
            body: {
              mode: 'raw',
              raw: JSON.stringify(definition.body, null, 2),
              options: { raw: { language: 'json' } },
            },
          }
        : {}),
      description: definition.description,
    },
    response: [],
    event: events,
  };
}

async function main(): Promise<void> {
  const openApi = JSON.parse(
    await readFile(resolve(process.cwd(), 'docs/openapi.yaml'), 'utf8'),
  ) as { paths: Record<string, Record<string, unknown>> };
  const documented = new Set(
    Object.entries(openApi.paths).flatMap(([path, methods]) =>
      Object.keys(methods).map((method) => `${method.toUpperCase()} ${path}`),
    ),
  );
  const included = new Set(
    groups
      .flatMap((group) => group.requests)
      .filter(
        (request) =>
          !request.path.startsWith('/health') &&
          request.path !== '/openapi.json' &&
          request.path !== '/metrics',
      )
      .map(
        (request) =>
          `${request.method} ${request.path
            .replace(/\{\{[^}]+\}\}/g, '{}')
            .replace(/\{[^}]+\}/g, '{}')}`,
      ),
  );
  const normalize = (route: string) => route.replace(/\{[^}]+\}/g, '{}');
  const normalizedIncluded = new Set([...included].map(normalize));
  const missing = [...documented].filter((route) => !normalizedIncluded.has(normalize(route)));
  if (missing.length > 0) {
    throw new Error(`Postman collection is missing OpenAPI routes: ${missing.join(', ')}`);
  }

  const collection = {
    info: {
      name: 'Amrutam Telemedicine API - Full Flow',
      description:
        'End-to-end Postman collection for local API, patient and doctor registration, MFA, booking, payments, prescriptions, admin, and operational endpoints. See postman/README.md before running.',
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    },
    variable: [{ key: 'baseUrl', value: 'http://localhost:3000' }],
    item: groups.map((group) => ({
      name: group.name,
      description: group.description,
      item: group.requests.map(createRequest),
    })),
  };
  const environment = {
    id: 'c67d3753-3171-4ad4-8e4f-4d14d7c041c0',
    name: 'Amrutam local',
    values: [
      { key: 'baseUrl', value: 'http://localhost:3000', type: 'default', enabled: true },
      ...environmentVariables.map((key) => ({
        key,
        value: '',
        type: 'secret' as const,
        enabled: true,
      })),
    ],
    _postman_variable_scope: 'environment',
    _postman_exported_at: new Date().toISOString(),
    _postman_exported_using: 'Amrutam Postman collection generator',
  };

  const outputDirectory = resolve(process.cwd(), 'postman');
  await mkdir(outputDirectory, { recursive: true });
  await Promise.all([
    writeFile(
      resolve(outputDirectory, 'Amrutam.postman_collection.json'),
      `${JSON.stringify(collection, null, 2)}\n`,
    ),
    writeFile(
      resolve(outputDirectory, 'Amrutam.local.postman_environment.json'),
      `${JSON.stringify(environment, null, 2)}\n`,
    ),
  ]);
  process.stdout.write(
    `Generated Postman collection with ${groups.reduce((count, group) => count + group.requests.length, 0)} requests.\n`,
  );
}

main().catch((error: unknown) => {
  console.error('Postman collection generation failed', error);
  process.exitCode = 1;
});
